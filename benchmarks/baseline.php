<?php

/**
 * Baseline exporter for the PhpBench suite.
 *
 * PhpBench's native storage (.phpbench/) is git-ignored and machine-specific,
 * so instead we export a portable, diff-friendly baseline that lives in the
 * repo: a JSON document per group under benchmarks/baselines/ plus a Markdown
 * summary. Commit these so future runs can be compared (`composer bench:diff`
 * or a manual read) and regressions caught in review.
 *
 * Usage:
 *   php benchmarks/baseline.php parse <group> <dump.xml> [<outDir>]
 *   php benchmarks/baseline.php readme [<outDir>]
 *
 * `parse` reads a PhpBench --dump-file XML and writes
 *   <outDir>/php<major><minor>-<group>.json
 * `readme` scans <outDir>/*.json and (re)writes <outDir>/README.md.
 */

declare(strict_types=1);

const DEFAULT_OUT_DIR = __DIR__ . '/baselines';

/**
 * @return array{php: string, generated: string, group: string, benchmarks: list<array<string, mixed>>}
 */
function parse_dump(string $group, string $xmlPath): array
{
    if (!is_file($xmlPath)) {
        fwrite(STDERR, "dump file not found: $xmlPath\n");
        exit(1);
    }

    $xml = simplexml_load_file($xmlPath);
    if ($xml === false) {
        fwrite(STDERR, "failed to parse XML: $xmlPath\n");
        exit(1);
    }

    $php  = (string) ($xml->suite->env->php->value[1] ?? '');
    $rows = [];

    foreach ($xml->suite->benchmark as $benchmark) {
        $class = (string) $benchmark['class'];

        foreach ($benchmark->subject as $subject) {
            $name = (string) $subject['name'];

            foreach ($subject->variant as $variant) {
                // NB: the element is <parameter-set> (hyphen) — SimpleXML needs brace syntax.
                $params = [];
                foreach ($variant->{'parameter-set'} as $set) {
                    foreach ($set->parameter as $parameter) {
                        $params[(string) $parameter['name']] = (string) $parameter['value'];
                    }
                }

                $mem = 0;
                $n   = 0;
                foreach ($variant->iteration as $iteration) {
                    $mem = max($mem, (int) $iteration['mem-peak']);
                    $n++;
                }

                if ($n === 0) {
                    continue;
                }

                // PhpBench emits per-variant <stats> (mean/mode/rstdev over the
                // per-revolution times); reuse them so the baseline matches the
                // aggregate report instead of re-deriving statistics.
                $stats = $variant->stats;

                $rows[] = [
                    'benchmark'      => ltrim($class, '\\'),
                    'subject'        => $name,
                    'params'         => $params,
                    'revs'           => (int) $variant['revs'],
                    'iterations'     => $n,
                    'time_avg_us'    => round((float) $stats['mean'], 3),
                    'mode_us'        => round((float) $stats['mode'], 3),
                    'rstdev_pct'     => round((float) $stats['rstdev'], 2),
                    'mem_peak_bytes' => $mem,
                ];
            }
        }
    }

    usort($rows, static fn (array $a, array $b): int =>
        [$a['benchmark'], $a['subject'], $a['params']] <=> [$b['benchmark'], $b['subject'], $b['params']]);

    return [
        'php'        => $php,
        'generated'  => gmdate('Y-m-d\TH:i:s\Z'),
        'group'      => $group,
        'benchmarks' => $rows,
    ];
}

function php_tag(string $version): string
{
    if (preg_match('/^(\d+)\.(\d+)/', $version, $m) === 1) {
        return 'php' . $m[1] . $m[2];
    }

    return 'php';
}

function cmd_parse(string $group, string $xmlPath, string $outDir): void
{
    $data = parse_dump($group, $xmlPath);
    @mkdir($outDir, 0o755, true);

    $file = sprintf('%s/%s-%s.json', $outDir, php_tag($data['php']), $group);
    file_put_contents($file, json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");

    printf("wrote %s (%d subjects, PHP %s)\n", $file, count($data['benchmarks']), $data['php']);
}

function cmd_readme(string $outDir): void
{
    $files = glob($outDir . '/*.json') ?: [];
    sort($files);

    $out = [];
    $out[] = '# Benchmark baselines';
    $out[] = '';
    $out[] = 'Portable, committed PhpBench baselines for regression tracking. Generated by';
    $out[] = '`composer bench:baseline:export` (see `benchmarks/baseline.php`). Times are the';
    $out[] = 'mean per-revolution wall time in microseconds; `rstdev` is the relative standard';
    $out[] = 'deviation across iterations. Regenerate after intentional performance changes and';
    $out[] = 'commit the diff.';
    $out[] = '';

    if ($files === []) {
        $out[] = '_No baselines generated yet._';
    }

    foreach ($files as $file) {
        $data = json_decode((string) file_get_contents($file), true);
        if (!is_array($data)) {
            continue;
        }

        $out[] = sprintf('## `%s` — group `%s` (PHP %s, %s)', basename($file), $data['group'], $data['php'], $data['generated']);
        $out[] = '';
        $out[] = '| Benchmark | Subject | Params | Revs | Mean (µs) | Mode (µs) | rstdev | Mem peak |';
        $out[] = '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |';

        foreach ($data['benchmarks'] as $row) {
            $params = $row['params'] === []
                ? '—'
                : implode(', ', array_map(static fn ($k, $v) => "$k=$v", array_keys($row['params']), array_values($row['params'])));

            $out[] = sprintf(
                '| %s | %s | %s | %d | %s | %s | %s%% | %s |',
                str_replace('Cassandra\\Benchmarks\\', '', $row['benchmark']),
                $row['subject'],
                $params,
                $row['revs'],
                number_format((float) $row['time_avg_us'], 3),
                number_format((float) ($row['mode_us'] ?? $row['time_avg_us']), 3),
                number_format((float) $row['rstdev_pct'], 2),
                format_bytes((int) $row['mem_peak_bytes']),
            );
        }
        $out[] = '';
    }

    $file = $outDir . '/README.md';
    file_put_contents($file, implode("\n", $out) . "\n");
    printf("wrote %s (%d baseline file(s))\n", $file, count($files));
}

function format_bytes(int $bytes): string
{
    if ($bytes >= 1024 * 1024) {
        return round($bytes / 1024 / 1024, 2) . ' MiB';
    }
    if ($bytes >= 1024) {
        return round($bytes / 1024, 1) . ' KiB';
    }

    return $bytes . ' B';
}

$argv0  = $argv[0];
$action = $argv[1] ?? '';

switch ($action) {
    case 'parse':
        $group  = $argv[2] ?? '';
        $xml    = $argv[3] ?? '';
        $outDir = $argv[4] ?? DEFAULT_OUT_DIR;
        if ($group === '' || $xml === '') {
            fwrite(STDERR, "usage: php $argv0 parse <group> <dump.xml> [<outDir>]\n");
            exit(2);
        }
        cmd_parse($group, $xml, $outDir);
        break;

    case 'readme':
        cmd_readme($argv[2] ?? DEFAULT_OUT_DIR);
        break;

    default:
        fwrite(STDERR, "usage:\n  php $argv0 parse <group> <dump.xml> [<outDir>]\n  php $argv0 readme [<outDir>]\n");
        exit(2);
}
